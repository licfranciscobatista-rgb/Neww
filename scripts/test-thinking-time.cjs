require('tsx/cjs');
const assert = require('node:assert/strict');
const { Chess } = require('chess.js');
const { estimateThinkingTime } = require('../src/engine/thinkingTime.ts');
const chess = new Chess();
const moves = [8, 10, 12, 14, 100].map(thinkTime => ({ source: 'MANUAL', thinkTime, timingMeasured: true, fenBefore: chess.fen() }));
const games = [{ playerColor: 'w', moves }];
const measured = estimateThinkingTime(chess, games, -1);
assert.equal(measured.basis, 'Tu ritmo');
assert.equal(measured.sampleCount, 5);
assert.equal(measured.recommendedSeconds, 9.6);
assert.equal(estimateThinkingTime(chess, [{ playerColor: 'w', moves: moves.map(m => ({ ...m, timingMeasured: undefined })) }], -1).basis, 'Estimación');
assert.equal(estimateThinkingTime(chess, [{ playerColor: 'b', moves }], -1).sampleCount, 0);
assert.equal(estimateThinkingTime(chess, [{ playerColor: 'w', moves: moves.map(m => ({ ...m, source: 'STOCKFISH_ASSISTED' })) }], -1).sampleCount, 0);
assert.equal(estimateThinkingTime(chess, games, 0).recommendedSeconds, 0);
assert.ok(estimateThinkingTime(chess, games, 2).recommendedSeconds <= 0.2);
assert.equal(estimateThinkingTime(chess, games, 30).urgency, 'critical');
assert.equal(estimateThinkingTime(chess, [{ playerColor: 'w', moves: moves.map(m => ({ ...m, thinkTime: NaN })) }], -1).basis, 'Estimación');
console.log('PASS: measured median, missing data, own side, assisted exclusions, invalid timing and low-clock budget.');
