require('tsx/cjs');
const assert = require('node:assert/strict');
const { RivalThinkingCache } = require('../src/engine/rivalThinking.ts');
const cache = new RivalThinkingCache();
const result = { uci: 'g8f6', scoreCp: 12, depth: 20, source: 'wasm' };
cache.reset('first');
cache.put('first', 'exact-fen', result);
assert.equal(cache.get('first', 'exact-fen'), result);
assert.equal(cache.get('first', 'different-fen'), undefined);
assert.equal(cache.get('other', 'exact-fen'), undefined);
cache.reset('second');
cache.put('first', 'stale-fen', result);
assert.equal(cache.get('second', 'exact-fen'), undefined);
assert.equal(cache.get('second', 'stale-fen'), undefined);
cache.put('second', 'fallback', { ...result, source: 'fallback' });
assert.equal(cache.get('second', 'fallback'), undefined);
for (let i = 0; i < 12; i++) cache.put('second', String(i), result);
assert.equal(cache.get('second', '0'), undefined);
assert.equal(cache.get('second', '11'), result);
console.log('Rival thinking: exact position reuse, stale game isolation and bounded cache passed.');
