const assert = require('node:assert/strict');
const { Chess } = require('chess.js');
const { mateSignal, legalVariation, drawReason, drawMoves } = require('../src/engine/endgameSignals.ts');
assert.equal(mateSignal({ mate: 5 }), true);
assert.equal(mateSignal({ mate: -3 }), true);
assert.equal(mateSignal({ mate: 6 }), false);
assert.equal(mateSignal({ scoreCp: 1000 }), false);
assert.equal(mateSignal(null), false);
assert.deepEqual(legalVariation(new Chess().fen(), 'e2e4 e7e5 invalid'), ['e4', 'e5']);
const repeated = new Chess();
['Nf3', 'Nf6', 'Ng1', 'Ng8', 'Nf3', 'Nf6', 'Ng1'].forEach(move => repeated.move(move));
const fen = repeated.fen(); const history = repeated.history();
assert.ok(drawMoves(repeated).some(move => move.san === 'Ng8' && move.reason === 'Triple repetición'));
assert.equal(repeated.fen(), fen);
assert.deepEqual(repeated.history(), history);
assert.equal(drawReason(new Chess('7k/5K2/6Q1/8/8/8/8/8 b - - 0 1')), 'Ahogado');
assert.equal(drawReason(new Chess('7k/8/6K1/8/8/8/8/8 w - - 0 1')), 'Material insuficiente');
assert.equal(drawReason(new Chess()), undefined);
console.log('PASS: mate threshold, legal PV, stalemate, material, repetition, board restoration.');
