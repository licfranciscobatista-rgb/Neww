require('tsx/cjs');
const assert = require('node:assert/strict');
const { aggregatePositionUsage, aggregateEngineUsageAndEffectiveness } = require('../src/engine/analyticsAggregator.ts');
const { saveGameRecord, loadGameRecords, resetPlayerProfile, deleteGameRecord } = require('../src/storage/chessStorage.ts');
const data = new Map();
global.localStorage = { getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value), removeItem: key => data.delete(key) };
const base = { id: 'regression', date: 'test', title: 'test', playerColor: 'w', result: '1/2-1/2', openingName: 'Test', moves: [], pgn: '', finalFen: '', movesCount: 0 };
assert.equal(aggregatePositionUsage([base])[0].winRate, 0);
assert.equal(aggregatePositionUsage([{ ...base, result: '1-0' }, { ...base, result: '*' }])[0].winRate, 100);
assert.equal(aggregateEngineUsageAndEffectiveness([], []).engineStats.MANUAL.percentageOfMoves, 0);
const rodentUsage = aggregateEngineUsageAndEffectiveness([{ ...base, moves: [{ source: 'RODENT_ASSISTED', ply: 1, fenBefore: '8/8/8/8/8/8/8/8 w - - 0 1' }] }], []);
assert.equal(rodentUsage.engineStats.RODENT_ASSISTED.count, 1);
assert.equal(rodentUsage.engineStats.MANUAL.count, 0);
saveGameRecord({ ...base, moves: [{ ply: 1, from: 'a7', to: 'a8', san: 'a8=Q', uci: 'a7a8q', source: 'MANUAL', thinkTime: 0, fenBefore: 'before', fenAfter: 'after' }] });
const saved = loadGameRecords().find(game => game.id === base.id);
assert.equal(saved.moves[0].thinkTime, 0);
assert.equal(saved.moves[0].uci, 'a7a8q');
assert.equal(saved.moves[0].fenBefore, 'before');
resetPlayerProfile();
assert.ok(loadGameRecords().some(game => game.id === base.id));
deleteGameRecord(base.id);
assert.ok(!loadGameRecords().some(game => game.id === base.id));
console.log('PASS: unfinished results, draw rates, empty adoption, zero timing, FEN, promotion, reset and deletion.');
