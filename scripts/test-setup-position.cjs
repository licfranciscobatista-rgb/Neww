require('tsx/cjs');
const assert = require('node:assert/strict');
const { Chess, DEFAULT_POSITION } = require('chess.js');
const { setupBoardFromFen, buildSetupFen, validateSetupPosition } = require('../src/engine/setupPosition.ts');
const { cloneChessWithHistory } = require('../src/utils/chessClone.ts');
const initial = setupBoardFromFen(DEFAULT_POSITION);
assert.equal(buildSetupFen(initial, 'w', 'KQkq', '-'), DEFAULT_POSITION);
assert.equal(validateSetupPosition(DEFAULT_POSITION), null);
assert.ok(validateSetupPosition(buildSetupFen({}, 'w', '', '-')));
const noKing = { ...initial }; delete noKing.e1;
assert.ok(validateSetupPosition(buildSetupFen(noKing, 'w', '', '-')));
assert.ok(validateSetupPosition('8/8/8/8/8/8/4k3/4K3 w - - 0 1'));
assert.ok(validateSetupPosition('4k3/8/8/8/8/8/8/4K3 w K - 0 1'));
assert.ok(validateSetupPosition('4k3/8/8/8/8/8/8/4K3 w - d6 0 1'));
assert.equal(validateSetupPosition('4k3/8/8/3pP3/8/8/8/4K3 w - d6 0 20'), null);
const fen = 'rnbqkbnr/pppppppp/8/8/4P3/8/PPPP1PPP/RNBQKBNR b KQkq - 0 1';
assert.equal(validateSetupPosition(fen), null);
const game = new Chess(fen);
game.move('e5'); game.move('Nf3');
const cloned = cloneChessWithHistory(game);
assert.equal(cloned.fen(), game.fen());
assert.equal(cloned.history().length, 2);
cloned.undo(); cloned.undo(); assert.equal(cloned.fen(), fen);
const pgn = game.pgn();
assert.ok(pgn.includes('[SetUp "1"]'));
const restored = new Chess(); restored.loadPgn(pgn);
assert.equal(restored.fen(), game.fen());
game.undo(); game.undo(); assert.equal(game.fen(), fen);
assert.equal(new Chess(fen).turn(), 'b');
console.log('PASS: setup round trip, kings, castling, en passant, turn, custom PGN and undo.');
