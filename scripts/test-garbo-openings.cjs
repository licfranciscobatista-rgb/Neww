const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { Chess } = require('chess.js');
const { OpeningIndex, OPENING_PRESETS, shouldPauseGarbo } = require('../src/engine/openingIndex.ts');
const entries = JSON.parse(fs.readFileSync(path.join(__dirname, '../public/openings/catalogue.json'), 'utf8'));
const started = performance.now();
const index = new OpeningIndex(entries);
entries.forEach((entry, i) => index.add(i));
for (const preset of OPENING_PRESETS) assert.ok(entries.some(e => e.name.includes(preset.pattern)), preset.name);
const initial = new Chess();
assert.equal(index.choose(initial.fen(), 'london').uci, 'd2d4');
assert.equal(index.choose(initial.fen(), 'italian').uci, 'e2e4');
assert.equal(index.choose(initial.fen(), 'free').status, 'free');
const italian = new Chess();
['e4', 'e5', 'Nf3', 'Nc6'].forEach(san => italian.move(san));
assert.equal(index.choose(italian.fen(), 'italian').uci, 'f1c4');
const diverted = new Chess();
['e4', 'c5'].forEach(san => diverted.move(san));
assert.equal(index.choose(diverted.fen(), 'italian').status, 'deviated');
assert.equal(shouldPauseGarbo('italian', index.choose(diverted.fen(), 'italian')), true);
assert.equal(shouldPauseGarbo('free', { status: 'free' }), false);
assert.equal(shouldPauseGarbo('london', { status: 'unavailable' }), true);
assert.equal(shouldPauseGarbo('london', { status: 'complete' }), true);
assert.equal(shouldPauseGarbo('italian', index.choose(italian.fen(), 'italian')), false);
assert.ok(index.choose(diverted.fen(), 'sicilian').uci, 'A paused Italian position offers a recognized Sicilian continuation');
assert.equal(shouldPauseGarbo('sicilian', index.choose(diverted.fen(), 'sicilian')), false);
diverted.undo();
diverted.move('e5');
assert.equal(shouldPauseGarbo('italian', index.choose(diverted.fen(), 'italian')), false);
diverted.undo();
diverted.move('c5');
assert.equal(index.choose(diverted.fen(), 'auto').status, 'book');
assert.match(index.choose(diverted.fen(), 'auto').detected, /Sicilian/);
const transposeA = new Chess(); const transposeB = new Chess();
['d4', 'Nf6', 'Nf3', 'd5', 'Bf4'].forEach(san => transposeA.move(san));
['d4', 'd5', 'Bf4', 'Nf6', 'Nf3'].forEach(san => transposeB.move(san));
assert.equal(index.choose(transposeA.fen(), 'london').uci, index.choose(transposeB.fen(), 'london').uci);
assert.ok(index.choose(transposeB.fen(), 'london').uci);
assert.equal(shouldPauseGarbo('london', index.choose(transposeB.fen(), 'london')), false);
const specific = entries.find(e => e.name.includes('Italian Game'));
const completed = new Chess(); completed.loadPgn(specific.pgn);
assert.equal(index.choose(completed.fen(), specific.id).status, 'complete');
const completedHistory = [completed.fen()];
completed.move(completed.moves()[0]);
assert.equal(index.choose(completed.fen(), specific.id, completedHistory).status, 'complete');
for (const preset of OPENING_PRESETS) {
  const choice = index.choose(initial.fen(), preset.id);
  const board = new Chess();
  assert.ok(board.move({ from: choice.uci.slice(0, 2), to: choice.uci.slice(2, 4), promotion: choice.uci[4] }));
}
const garboSource = fs.readFileSync(path.join(__dirname, '../src/engine/garboEngine.ts'), 'utf8');
assert.ok(!/stockfish/i.test(garboSource));
console.log(`PASS: ${entries.length} lines, presets, legal moves, Italian deviation, automatic detection, transpositions, completion, independence. Index: ${Math.round(performance.now() - started)}ms.`);
